# ------------------------------------------------------------------ 导出标识

# 导出产物里写入的生成者标识。改动这段会让导出的 PDF/PNG/SVG 里带不同信息，
# 因此它也是一条"来源痕迹"：别人改了工具名，用它导出的文件里仍写着原工具。
XH_PRODUCER = "小黄OFD (xiaohuang-ofd) · github.com/MrY551/xiaohuangOFD"


def _producer() -> str:
    """带版本与构建指纹，便于把一份导出产物追溯到具体版本。"""
    try:
        from .buildid import build_id
        return XH_PRODUCER + " · " + build_id()
    except Exception:
        return XH_PRODUCER


# ------------------------------------------------------------------ PDF

def export_pdf(pkg: model.OFDPackage, path: str, dpi: int = 200,
               pages: Optional[List[int]] = None, progress=None) -> str:
    """导出 PDF。pages 是 0 基页码列表，None 表示全部。"""
    from .render_pil import PilRenderer
    all_pages = pkg.all_pages()
    idx = list(range(len(all_pages))) if pages is None else list(pages)
    idx = [i for i in idx if 0 <= i < len(all_pages)]
    if not idx:
        raise RenderError("没有可导出的页面")
    imgs = []
    for n, i in enumerate(idx):
        page = all_pages[i]
        sc = build_page_scene(page)
        r = PilRenderer(dpi=dpi)
        r.load_resources(sc.resources)
        img = r.render(sc)
        imgs.append(img.convert("RGB") if img.mode != "RGB" else img)
        if progress:
            progress(n + 1, len(idx))
    buf = io.BytesIO()
    first = imgs[0]
    rest = imgs[1:]
    prod = _producer()
    first.save(buf, format="PDF", resolution=float(dpi), save_all=True,
               append_images=rest, title=pkg.document.title or "OFD",
               # PDF 元数据：Producer/Creator/Author 会留在文件里，可被 pdfinfo 读到
               producer=prod, creator=prod, author="小黄 <15359927763>",
               subject="Generated by 小黄OFD")
    data = buf.getvalue()
    tmp = path + ".tmp"
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, path)
    return path


def export_png_single(page: model.Page, path: str, dpi: int = 150) -> str:
    from .render_pil import render_page
    img, _warn = render_page(page, dpi=dpi)
    # PNG tEXt 块：文件属性里能看到生成者，改工具名不影响这一段
    from PIL import PngImagePlugin
    meta = PngImagePlugin.PngInfo()
    meta.add_text("Software", _producer())
    meta.add_text("Author", "小黄 <15359927763>")
    img.save(path, pnginfo=meta)
    return path


# ------------------------------------------------------------------ SVG

def _num(v: float) -> str:
    s = ("%.3f" % float(v)).rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def _svg_color(rgba, as_stroke: bool = False) -> str:
    if not rgba:
        return "none"
    r, g, b, a = rgba
    hexv = "#%02x%02x%02x" % (int(r * 255), int(g * 255), int(b * 255))
    if a >= 0.999:
        return hexv
    if as_stroke:
        return hexv
    return hexv


def page_to_svg(page: model.Page, scene: Optional[PageScene] = None,
                inline_images: bool = True) -> str:
    """单页 → SVG 字符串。单位 mm，viewBox 用 mm 数值。"""
    sc = scene or build_page_scene(page)
    w, h = sc.size.w, sc.size.h
    out = []
    out.append('<?xml version="1.0" encoding="UTF-8"?>')
    # SVG 注释：生成者标识，改工具名不会带走这一段
    out.append('<!-- Generated by %s -->\n' % _producer())
    out.append('<svg xmlns="http://www.w3.org/2000/svg" '
               'xmlns:xlink="http://www.w3.org/1999/xlink" '
               'width="%smm" height="%smm" viewBox="0 0 %s %s" '
               'shape-rendering="geometricPrecision">'
               % (_num(w), _num(h), _num(w), _num(h)))
    out.append('<title>%s</title>' % _escape(page.id))
    for op in sc.ops:
        t = op.get("t")
        if t == "rect":
            fill = _svg_color(op.get("fill"))
            stroke = _svg_color(op.get("stroke"))
            out.append('<rect x="%s" y="%s" width="%s" height="%s" fill="%s" stroke="%s"/>'
                       % (_num(op["x"]), _num(op["y"]), _num(op["w"]), _num(op["h"]),
                          fill, stroke))
        elif t == "path":
            d = _svg_path_d(op)
            fill = _svg_color(op.get("fill"))
            stroke = _svg_color(op.get("stroke"))
            dash = op.get("dash")
            dash_attr = (' stroke-dasharray="%s"' % " ".join(_num(v) for v in dash)) if dash else ""
            rule = "evenodd" if op.get("rule") == "evenodd" else "nonzero"
            out.append('<path d="%s" fill="%s" stroke="%s" stroke-width="%s"'
                       ' fill-rule="%s" stroke-linejoin="round" stroke-linecap="round"%s/>'
                       % (d, fill, stroke if stroke != "none" else "none",
                          _num(op.get("w", 0.2)) if stroke != "none" else "0", rule, dash_attr))
        elif t == "text":
            txt = op.get("text") or ""
            if not txt:
                continue
            color = _svg_color(op.get("color"))
            size = op.get("size", 3.0)
            rot = op.get("rot") or 0.0
            transform = ""
            if abs(rot) > 0.01:
                transform = ' transform="rotate(%s %s %s)"' % (
                    _num(rot), _num(op["x"]), _num(op["y"]))
            spacing = op.get("spacing") or 0
            sp_attr = ' letter-spacing="%s"' % _num(spacing) if spacing else ""
            weight = ' font-weight="bold"' if op.get("bold") else ""
            style = ' font-style="italic"' if op.get("italic") else ""
            out.append('<text x="%s" y="%s" font-family="%s" font-size="%s" '
                       'fill="%s"%s%s%s%s>%s</text>'
                       % (_num(op["x"]), _num(op["y"]), _escape(op.get("font") or "sans-serif"),
                          _num(size), color, weight, style, sp_attr, transform, _escape(txt)))
        elif t == "image":
            res = sc.resources.get(op.get("res") or "")
            if not res:
                continue
            corners = op.get("corners") or []
            x, y, iw, ih = op["x"], op["y"], op["w"], op["h"]
            data = res.get("data") or ""
            if not data and inline_images:
                continue
            if len(corners) == 4:
                # 用四角构造仿射（左上、右上、左下）
                p0, p1, _p2, p3 = corners
                a = (p1[0] - p0[0]) / iw if iw else 1
                b = (p1[1] - p0[1]) / iw if iw else 0
                c = (p3[0] - p0[0]) / ih if ih else 0
                d = (p3[1] - p0[1]) / ih if ih else 1
                tr = ' transform="matrix(%s %s %s %s %s %s)"' % (
                    _num(a), _num(b), _num(c), _num(d), _num(p0[0]), _num(p0[1]))
                out.append('<image x="0" y="0" width="%s" height="%s"%s '
                           'preserveAspectRatio="none" xlink:href="data:%s;base64,%s"/>'
                           % (_num(iw), _num(ih), tr, res.get("mime", "image/png"), data))
            else:
                out.append('<image x="%s" y="%s" width="%s" height="%s" '
                           'preserveAspectRatio="none" xlink:href="data:%s;base64,%s"/>'
                           % (_num(x), _num(y), _num(iw), _num(ih),
                              res.get("mime", "image/png"), data))
    out.append('</svg>')
    return "\n".join(out)


def _svg_path_d(op: dict) -> str:
    parts = []
    subs = op.get("subs") or []
    closed = op.get("closed") or [False] * len(subs)
    for i, arr in enumerate(subs):
        if len(arr) < 2:
            continue
        parts.append("M %s %s" % (_num(arr[0]), _num(arr[1])))
        for k in range(2, len(arr) - 1, 2):
            parts.append("L %s %s" % (_num(arr[k]), _num(arr[k + 1])))
        if i < len(closed) and closed[i]:
            parts.append("Z")
    return " ".join(parts)


def _escape(s: str) -> str:
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def export_svg(page: model.Page, path: str = "") -> str:
    svg = page_to_svg(page)
    if path:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(svg)
    return svg


# ------------------------------------------------------------------ 文本

def export_text(pkg: model.OFDPackage, path: str = "") -> str:
    """按页面、按对象顺序抽文本。"""
    lines = []
    for i, page in enumerate(pkg.all_pages()):
        lines.append("=== 第 %d 页 ===" % (i + 1))
        for obj in page.objects():
            if isinstance(obj, model.TextObject):
                t = obj.text()
                if t.strip():
                    lines.append(t)
        lines.append("")
    text = "\n".join(lines)
    if path:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    return text


# ------------------------------------------------------------------ 结构报告

def structure_report(pkg: model.OFDPackage) -> dict:
    """给界面/CLI 用的结构摘要。"""
    docs = []
    for d in pkg.documents:
        pages = []
        for i, p in enumerate(d.pages):
            objs = p.objects()
            kinds: Dict[str, int] = {}
            for o in objs:
                kinds[o.type_name] = kinds.get(o.type_name, 0) + 1
            pages.append({
                "index": i,
                "id": p.id,
                "size": [round(p.size().w, 2), round(p.size().h, 2)],
                "rotation": p.rotation(),
                "layers": len(p.layers),
                "objects": len(objs),
                "kinds": kinds,
                "fonts": sorted(set(o.font_id() for o in objs
                                    if isinstance(o, model.TextObject) and o.font_id())),
                "baseloc": p.base_loc,
            })
        docs.append({
            "entry": d.entry,
            "title": d.title,
            "author": d.author,
            "pages": pages,
            "public_res": [r.entry for r in d.public_res],
            "doc_res": d.doc_res.entry if d.doc_res else None,
            "fonts": {f.id: f.display_name()
                      for r in d.public_res for f in r.fonts.values()},
            "images": d.doc_res.multimedia if d.doc_res else {},
        })
    return {
        "path": pkg.path,
        "entries": len(pkg.entries),
        "documents": len(pkg.documents),
        "pages": pkg.page_count(),
        "docs": docs,
        "files": sorted(pkg.entries.keys()),
    }
